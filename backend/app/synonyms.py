# 高频疑问词：不参与扩展，避免噪声
STOP_QUERY_WORDS = ("什么", "多少", "吗", "呢", "有要求", "如何", "怎么", "哪些")


def expand(query: str, max_terms: int = 8) -> str:
    """在查询后追加同义词，仅用于检索（送给模型的问题保持原样）。"""
    extra: list[str] = []
    for key, words in DOMAIN_SYNONYMS.items():
        if key in query:
            for w in words:
                if w not in query and w not in extra:
                    extra.append(w)
    return query + ("　" + "　".join(extra[:max_terms]) if extra else "")
